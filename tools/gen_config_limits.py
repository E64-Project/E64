#!/usr/bin/env python3
"""Export Config display limits from the native header for the Web UI."""
from pathlib import Path
import re,json
ROOT=Path(__file__).resolve().parents[1]
text=(ROOT/'src/configs/configs.h').read_text()
limit=int(re.search(r'^#define CONFIGS_MAX_NAME_LEN (\d+)$',text,re.M)[1])
out='// Generated by tools/gen_config_limits.py from src/configs/configs.h.\n'
out+=f'export const MAX_CONFIG_NAME = {limit};\n'
path=ROOT/'src/webui/assets/js/config_limits.js'
if not path.exists() or path.read_text()!=out:path.write_text(out)
